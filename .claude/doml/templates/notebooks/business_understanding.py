@app.cell
def _(PROJECT_ROOT, config, mo, re):
    with mo.redirect_stdout():
        import duckdb
        import pandas as pd

        data_dir = PROJECT_ROOT / 'data' / 'raw'

        SUPPORTED = {'.csv', '.parquet', '.xlsx'}
        files = sorted([f for f in data_dir.glob('**/*') if f.is_file() and f.suffix.lower() in SUPPORTED])

        if not files:
            print(f"No supported files found in {data_dir}")
            print("Supported formats: CSV (.csv), Parquet (.parquet), Excel (.xlsx)")
        else:
            for path in files:
                con = duckdb.connect()
                p = str(path)
                ext = path.suffix.lower()

                if ext == '.csv':
                    schema_df = con.execute(f"DESCRIBE SELECT * FROM read_csv_auto('{p}')").df()
                    row_count = con.execute(f"SELECT COUNT(*) FROM read_csv_auto('{p}')").fetchone()[0]
                    sample_df = con.execute(f"SELECT * FROM read_csv_auto('{p}') LIMIT 3").df()
                elif ext == '.parquet':
                    schema_df = con.execute(f"DESCRIBE SELECT * FROM read_parquet('{p}')").df()
                    row_count = con.execute(f"SELECT COUNT(*) FROM read_parquet('{p}')").fetchone()[0]
                    sample_df = con.execute(f"SELECT * FROM read_parquet('{p}') LIMIT 3").df()
                elif ext == '.xlsx':
                    schema_df = con.execute(f"DESCRIBE SELECT * FROM read_xlsx('{p}')").df()
                    row_count = con.execute(f"SELECT COUNT(*) FROM read_xlsx('{p}')").fetchone()[0]
                    sample_df = con.execute(f"SELECT * FROM read_xlsx('{p}') LIMIT 3").df()

                cols = schema_df['column_name'].tolist()

                # Detect headerless CSV — DuckDB names columns column0, column1, ... when no header row
                auto_named = ext == '.csv' and all(re.match(r'^column\d+$', c) for c in cols)
                if auto_named:
                    user_names = config.get('column_names', {}).get(path.stem) or \
                                 config.get('column_names', {}).get(path.name)
                    if user_names:
                        # Re-read with user-supplied names (header=false so DuckDB doesn't consume row 1)
                        names_sql = '[' + ', '.join(f"'{n}'" for n in user_names) + ']'
                        schema_df = con.execute(
                            f"DESCRIBE SELECT * FROM read_csv('{p}', header=false, names={names_sql})"
                        ).df()
                        sample_df = con.execute(
                            f"SELECT * FROM read_csv('{p}', header=false, names={names_sql}) LIMIT 3"
                        ).df()
                        cols = schema_df['column_name'].tolist()
                        mo.output.append(mo.md(
                            f'> **Note:** `{path.name}` has no header row. '
                            f'Column names loaded from `config.json` → `column_names.{path.stem}`.'
                        ))
                    else:
                        mo.output.append(mo.md(
                            f'> ⚠️ **`{path.name}` has no header row** — DuckDB assigned names '
                            f'`{", ".join(cols)}`.  \n'
                            f'> Add column names to `.planning/config.json` under `"column_names"` '
                            f'so the analysis uses meaningful names:  \n'
                            f'> ```json\n'
                            f'> {{"column_names": {{"{path.stem}": ["col1", "col2", ...]}}}}\n'
                            f'> ```\n'
                            f'> Then re-run `/doml-execute-phase 1`.'
                        ))

                # Null counts — dynamic query across all columns
                null_exprs = ', '.join(
                    f'SUM(CASE WHEN "{c}" IS NULL THEN 1 ELSE 0 END) AS "{c}"'
                    for c in cols
                )
                if ext == '.csv':
                    user_names = config.get('column_names', {}).get(path.stem) or \
                                 config.get('column_names', {}).get(path.name)
                    if auto_named and user_names:
                        names_sql = '[' + ', '.join(f"'{n}'" for n in user_names) + ']'
                        null_df = con.execute(
                            f"SELECT {null_exprs} FROM read_csv('{p}', header=false, names={names_sql})"
                        ).df()
                    else:
                        null_df = con.execute(f"SELECT {null_exprs} FROM read_csv_auto('{p}')").df()
                elif ext == '.parquet':
                    null_df = con.execute(f"SELECT {null_exprs} FROM read_parquet('{p}')").df()
                elif ext == '.xlsx':
                    null_df = con.execute(f"SELECT {null_exprs} FROM read_xlsx('{p}')").df()
                con.close()

                null_summary = null_df.T.rename(columns={0: 'null_count'})
                null_summary['null_pct'] = (null_summary['null_count'] / row_count * 100).round(1)

                mo.output.append(mo.md(f'### {path.name}'))
                print(f'Shape: {row_count:,} rows × {len(cols)} columns')

                mo.output.append(mo.md('**Schema:**'))
                mo.output.append(schema_df[['column_name', 'column_type']].rename(
                    columns={'column_name': 'Column', 'column_type': 'Type'}
                ))

                mo.output.append(mo.md('**Sample rows (3):**'))
                mo.output.append(sample_df)

                mo.output.append(mo.md('**Null counts:**'))
                mo.output.append(null_summary)
                print()
    return


