@app.cell
def _(PROJECT_ROOT, duckdb, files, get_read_fn, mo, pd):
    with mo.redirect_stdout():
        processed_dir = PROJECT_ROOT / 'data' / 'processed'
        processed_dir.mkdir(parents=True, exist_ok=True)  # safe: data/raw/ is read-only (INFR-05)

        for _path in files:
            _con = duckdb.connect()
            _read_fn = get_read_fn(_path)
            _df = _con.execute(f"SELECT * FROM {_read_fn}").df()
            _con.close()

            # Parse unambiguous date string columns
            date_cols_parsed = []
            for _col in _df.select_dtypes(include=['object', 'string']).columns:
                sample = _df[_col].dropna().head(20)
                if len(sample) == 0:
                    continue
                try:
                    pd.to_datetime(sample, format='mixed', errors='raise')
                    _df = _df.copy()
                    _df[_col] = pd.to_datetime(_df[_col], format='mixed', errors='coerce')
                    date_cols_parsed.append(_col)
                except Exception:
                    pass

            out_path = processed_dir / _path.name
            ext = _path.suffix.lower()
            if ext == '.csv':
                _df.to_csv(out_path, index=False)
            elif ext == '.parquet':
                _df.to_parquet(out_path, index=False)
            elif ext == '.xlsx':
                _df.to_excel(out_path, index=False)

            print(f"{_path.name}:")
            print(f"  Shape:   {len(_df):,} rows \u00d7 {len(_df.columns)} columns")
            if date_cols_parsed:
                print(f"  Parsed date columns: {date_cols_parsed}")
            print(f"  Written: {out_path}")
            print()
    return


