@app.cell
def _(PROJECT_ROOT, column_names, mo, table):
    with mo.redirect_stdout():
        import duckdb
        import pandas as pd

        data_dir = PROJECT_ROOT / 'data' / 'raw'
        SUPPORTED = {'.csv', '.parquet', '.xlsx'}
        files = sorted([f for f in data_dir.glob('**/*') if f.is_file() and f.suffix.lower() in SUPPORTED])

        if not files:
            print(f"No supported files found in {data_dir}")
            print("Supported formats: CSV (.csv), Parquet (.parquet), Excel (.xlsx)")
        else:
            print(f"Found {len(files)} file(s) in data/raw/:")
            for _path in files:
                print(f"  {_path.name}")

        def get_read_fn(_path):
            """Return a DuckDB read-function fragment for the given file.
        Applies user-supplied column names from config.column_names for headerless CSVs."""
            p = str(_path)
            ext = _path.suffix.lower()
            if ext == '.csv':
                user_names = column_names.get(_path.stem) or column_names.get(_path.name)
                if user_names:
                    names_sql = '[' + ', '.join(f"'{n}'" for n in user_names) + ']'
                    return f"read_csv('{p}', header=false, names={names_sql})"
                return f"read_csv_auto('{p}')"
            elif ext == '.parquet':
                return f"read_parquet('{p}')"
            elif ext == '.xlsx':
                return f"read_xlsx('{p}')"

        for _path in files:
            _con = duckdb.connect()
            _read_fn = get_read_fn(_path)

            _schema_df = _con.execute(f"DESCRIBE SELECT * FROM {_read_fn}").df()
            _row_count = _con.execute(f"SELECT COUNT(*) FROM {_read_fn}").fetchone()[0]
            _cols = _schema_df['column_name'].tolist()

            null_exprs = ', '.join(
                f"SUM(CASE WHEN \"{c}\" IS NULL THEN 1 ELSE 0 END) AS \"{c}\""
                for c in _cols
            )
            null_df = _con.execute(f"SELECT {null_exprs} FROM {_read_fn}").df().T.rename(columns={0: 'null_count'})
            null_df['null_pct'] = (null_df['null_count'] / _row_count * 100).round(1)
            _con.close()

            mo.output.append(mo.md(f"### {_path.name}"))
            print(f"Shape: {_row_count:,} rows \u00d7 {len(_cols)} columns")
            mo.output.append(mo.md("**Schema (DuckDB DESCRIBE):**"))
            mo.output.append(table(_schema_df[['column_name', 'column_type']].rename(columns={'column_name': 'Column', 'column_type': 'Type'})))
            has_nulls = null_df[null_df['null_count'] > 0]
            if len(has_nulls) > 0:
                mo.output.append(mo.md("**Null counts (columns with nulls only):**"))
                mo.output.append(table(has_nulls))
            else:
                print("\u2713 No null values found")
            print()
    return duckdb, files, get_read_fn, pd


