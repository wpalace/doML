@app.cell
def _(config, dfs, mo, plt):
    with mo.redirect_stdout():
        from statsmodels.tsa.stattools import adfuller, kpss
        from statsmodels.tsa.seasonal import seasonal_decompose

        time_factor = config.get('time_factor', False)

        if not time_factor:
            print("time_factor = False \u2014 time series analysis skipped.")
            print("To enable: set time_factor=true in .planning/config.json")
        else:
            mo.output.append(mo.md("### Time Series Stationarity & Decomposition"))

            for _fname, _df in dfs.items():
                _numeric_cols = _df.select_dtypes(include='number').columns.tolist()
                if not _numeric_cols:
                    print(f"{_fname}: No numeric columns for time series tests")
                    continue

                mo.output.append(mo.md(f"#### {_fname}"))

                for ts_col in _numeric_cols[:2]:
                    _series = _df[ts_col].dropna().reset_index(drop=True)
                    if len(_series) < 20:
                        print(f"  {ts_col}: Too few observations (n={len(_series)}) \u2014 skipping")
                        continue

                    mo.output.append(mo.md(f"**`{ts_col}` (n={len(_series)})**"))

                    # ADF test (H0: unit root = non-stationary)
                    try:
                        adf = adfuller(_series, autolag='AIC')
                        print(f"ADF Test  \u2014 statistic: {adf[0]:.4f}, p-value: {adf[1]:.4f}, lags: {adf[2]}")
                        for cv_k, cv_v in adf[4].items():
                            print(f"           critical value {cv_k}: {cv_v:.3f}")
                        interp = 'STATIONARY (reject H0, p<0.05)' if adf[1] < 0.05 else 'NON-STATIONARY (fail to reject H0)'
                        print(f"           \u2192 {interp}")
                    except Exception as e:
                        print(f"  ADF failed: {e}")

                    # KPSS test (H0: stationary)
                    try:
                        kp = kpss(_series, regression='c', nlags='auto')
                        print(f"\nKPSS Test \u2014 statistic: {kp[0]:.4f}, p-value: {kp[1]:.4f}")
                        interp = 'NON-STATIONARY (reject H0, p<0.05)' if kp[1] < 0.05 else 'STATIONARY (fail to reject H0)'
                        print(f"           \u2192 {interp}")
                    except Exception as e:
                        print(f"  KPSS failed: {e}")

                    # Seasonal decomposition (requires >= 2*period obs)
                    try:
                        period = 12
                        if len(_series) >= 2 * period:
                            decomp = seasonal_decompose(_series, model='additive', period=period, extrapolate_trend='freq')
                            _fig, _axes = plt.subplots(4, 1, figsize=(12, 8), sharex=True)
                            decomp.observed.plot(ax=_axes[0], title='Observed', color='steelblue')
                            decomp.trend.plot(ax=_axes[1], title='Trend', color='darkorange')
                            decomp.seasonal.plot(ax=_axes[2], title='Seasonal', color='green')
                            decomp.resid.plot(ax=_axes[3], title='Residual', color='gray')
                            _fig.suptitle(f'{ts_col} \u2014 Seasonal Decomposition (period={period})', fontsize=11)
                            plt.tight_layout()
                            mo.output.append(plt.gcf()); plt.close()
                        else:
                            print(f"\n  Decomposition skipped: need >= {2*period} obs, have {len(_series)}")
                    except Exception as e:
                        print(f"\n  Decomposition failed: {e}")
                    print()
    return


