@app.cell
def _(dfs, mo, pd, table):
    with mo.redirect_stdout():
        import re

        for _fname, _df in dfs.items():
            mo.output.append(mo.md(f"### {_fname} \u2014 Tidy Validation"))
            issues = []

            # Check 1: Duplicate rows
            dup_count = _df.duplicated().sum()
            if dup_count > 0:
                mo.output.append(mo.md(f"**[VIOLATION] Duplicate rows: {dup_count} exact duplicates**"))
                mo.output.append(table(_df[_df.duplicated(keep=False)].head(3)))
                issues.append(f"Duplicate rows ({dup_count}) \u2014 action: `df.drop_duplicates()` before modelling")
            else:
                print("\u2713 No duplicate rows")

            # Check 2: Multiple values in one cell (>5% of non-null values contain ,;|)
            multi_cols = []
            for _col in _df.select_dtypes(include=['object', 'string']).columns:
                non_null = _df[_col].dropna()
                if len(non_null) == 0:
                    continue
                _pct = non_null.str.contains(r'[,;|]', regex=True, na=False).mean()
                if _pct > 0.05:
                    multi_cols.append({'column': _col, 'pct_multi_value': round(_pct * 100, 1)})
            if multi_cols:
                mo.output.append(mo.md(f"**[VIOLATION] Multi-value cells (>5% contain comma/semicolon/pipe):**"))
                mo.output.append(table(pd.DataFrame(multi_cols)))
                issues.append(f"Multi-value columns: {[r['column'] for r in multi_cols]} \u2014 split into separate rows/columns")
            else:
                print("\u2713 No multi-value cells detected")

            # Check 3: Mixed observation types (column-name prefix heuristic)
            prefixes = {}
            for _col in _df.columns:
                prefix = _col.split('_')[0].lower() if '_' in _col else _col[:4].lower()
                prefixes[prefix] = prefixes.get(prefix, 0) + 1
            dominant = {p for p, c in prefixes.items() if c >= 2}
            if len(dominant) >= 3:
                mo.output.append(mo.md(
                    f"**[POTENTIAL VIOLATION] Mixed entity types:** {len(dominant)} column-name prefixes suggest "
                    f"multiple entity types \u2014 `{'`, `'.join(sorted(dominant)[:5])}`"
                ))
                issues.append("Mixed entity column prefixes \u2014 verify table does not combine multiple entities")
            else:
                print("\u2713 No obvious mixed entity types")

            if issues:
                mo.output.append(mo.md("\n**Tidy violations summary \u2014 remediate before feature engineering:**"))
                for iss in issues:
                    print(f"  \u2022 {iss}")
            else:
                print(f"\n\u2713 {_fname}: All tidy checks passed")
            print()
    return


