@app.cell
def _(dfs, mo, np, pd, table):
    with mo.redirect_stdout():
        from scipy.stats import chi2_contingency, pointbiserialr

        def cramers_v(x, y):
            """Cram\u00e9r's V for two categorical Series."""
            ct = pd.crosstab(x, y)
            chi2, _, _, _ = chi2_contingency(ct)
            n = ct.values.sum()
            phi2 = chi2 / n
            r, k = ct.shape
            denom = min(k - 1, r - 1)
            return float(np.sqrt(phi2 / denom)) if denom > 0 else 0.0

        def is_categorical(series, threshold=0.1):
            # pandas 3 stores text as the `str` dtype (not `object`), so test "not numeric".
            return (not pd.api.types.is_numeric_dtype(series) or
                    series.nunique() < max(10, len(series) * threshold))

        def as_binary_float(series):
            # 0/1 codes for any two-level column (numbers, text or booleans).
            return pd.Series(pd.factorize(series, sort=True)[0], index=series.index).astype(float)

        def is_binary(series):
            return series.nunique() == 2

        for _fname, _df in dfs.items():
            mo.output.append(mo.md(f"### {_fname} \u2014 Correlation Analysis"))

            # Pearson matrix for numeric columns
            _num_df = _df.select_dtypes(include='number')
            if len(_num_df.columns) >= 2:
                corr_matrix = _num_df.corr(method='pearson')
                mo.output.append(mo.md("**Pearson Correlation (numeric features):**"))
                mo.output.append(table(corr_matrix.round(3)))

            # Mixed-type correlations
            _cols = _df.columns.tolist()
            mixed_results = []
            for _i, c1 in enumerate(_cols):
                for c2 in _cols[_i + 1:]:
                    s1 = _df[c1].dropna()
                    s2 = _df[c2].dropna()
                    common = s1.index.intersection(s2.index)
                    s1, s2 = s1[common], s2[common]
                    if len(s1) < 10:
                        continue
                    if (pd.api.types.is_datetime64_any_dtype(s1)
                            or pd.api.types.is_datetime64_any_dtype(s2)):
                        continue  # time columns are handled in the time series section

                    cat1, cat2 = is_categorical(s1), is_categorical(s2)
                    bin1, bin2 = is_binary(s1), is_binary(s2)

                    if cat1 and cat2:
                        v = cramers_v(s1, s2)
                        mixed_results.append({'col1': c1, 'col2': c2, 'method': "Cram\u00e9r's V", 'value': round(v, 3)})
                    elif not cat1 and bin2:
                        r_val, p_val = pointbiserialr(as_binary_float(s2), s1.astype(float))
                        mixed_results.append({'col1': c1, 'col2': c2, 'method': 'point-biserial', 'value': round(r_val, 3), 'p': round(p_val, 4)})
                    elif bin1 and not cat2:
                        r_val, p_val = pointbiserialr(as_binary_float(s1), s2.astype(float))
                        mixed_results.append({'col1': c1, 'col2': c2, 'method': 'point-biserial', 'value': round(r_val, 3), 'p': round(p_val, 4)})

            if mixed_results:
                mo.output.append(mo.md("**Mixed-type correlations:**"))
                mo.output.append(table(pd.DataFrame(mixed_results)))
            else:
                print("No mixed-type column pairs detected (or all numeric \u2014 see Pearson matrix above)")
    return


