@app.cell
def _(table, 
    SEED,
    StratifiedKFold,
    X_train,
    cross_validate,
    cv_scoring,
    is_binary,
    mo,
    models,
    n_folds,
    pd,
    primary_label,
    y_train,
):
    with mo.redirect_stdout():
        skf = StratifiedKFold(n_splits=n_folds, shuffle=True, random_state=SEED)
        leaderboard_rows = []

        # Store fitted models and first-split data for SHAP
        fitted_models = {}
        shap_data_dict = {}

        for _name, _model in models.items():
            scores = cross_validate(
                _model, X_train, y_train, cv=skf, n_jobs=-1,
                scoring=cv_scoring,
                return_estimator=True,
                return_train_score=False,
            )

            primary_key = 'test_auc' if is_binary else 'test_f1_macro'
            primary_mean = scores[primary_key].mean()
            primary_std  = scores[primary_key].std()

            if is_binary:
                f1_mean  = scores['test_f1'].mean()
                acc_mean = scores['test_accuracy'].mean()
            else:
                f1_mean  = scores['test_f1_weighted'].mean()
                acc_mean = scores['test_accuracy'].mean()

            leaderboard_rows.append({
                'model':              _name,
                'cv_primary_mean':    round(primary_mean, 4),
                'cv_primary_std':     round(primary_std, 4),
                'cv_f1_mean':         round(f1_mean, 4),
                'cv_accuracy_mean':   round(acc_mean, 4),
                'test_score':         None,
                'note':               'CV',
            })

            # Save first-fold fitted model + validation split for SHAP
            _first_split = list(skf.split(X_train, y_train))[0]
            __, _val_idx = _first_split
            X_val_shap = X_train.iloc[_val_idx]
            fitted_models[_name] = scores['estimator'][0]
            shap_data_dict[_name] = X_val_shap

            print(f"{_name:35s}  {primary_label}={primary_mean:.4f} ±{primary_std:.4f}  F1={f1_mean:.4f}  Acc={acc_mean:.4f}")

        # Sort descending (higher is better for classification)
        leaderboard = pd.DataFrame(leaderboard_rows).sort_values('cv_primary_mean', ascending=False).reset_index(drop=True)
        print(f"\n--- LEADERBOARD (sorted by {primary_label}) ---")
        mo.output.append(table(leaderboard[['model','cv_primary_mean','cv_primary_std','cv_f1_mean','cv_accuracy_mean']]))
    return fitted_models, leaderboard, shap_data_dict, skf


