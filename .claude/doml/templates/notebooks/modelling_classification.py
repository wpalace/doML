@app.cell
def _(table, 
    X_test,
    accuracy_score,
    f1_score,
    is_binary,
    leaderboard_1,
    mo,
    pd,
    roc_auc_score,
    tuned_df,
    tuned_models,
    y_test,
):
    with mo.redirect_stdout():
        best_tuned_name = tuned_df.sort_values('cv_primary_mean', ascending=False).iloc[0]['model']  # Best tuned model = highest cv_primary_mean among tuned models
        base_name = best_tuned_name.replace(' (tuned)', '')
        best_model = tuned_models[base_name]
        y_pred_test = best_model.predict(X_test)
        if is_binary:
            y_prob_test = best_model.predict_proba(X_test)[:, 1]
            test_primary = roc_auc_score(y_test, y_prob_test)
            primary_name = 'ROC-AUC'
        else:
            test_primary = f1_score(y_test, y_pred_test, average='macro')
            primary_name = 'Macro F1'
        test_acc = accuracy_score(y_test, y_pred_test)
        test_f1 = f1_score(y_test, y_pred_test, average='weighted')
        print(f'Best model: {best_tuned_name}')
        print(f'Test {primary_name}: {test_primary:.4f}')
        print(f'Test Accuracy: {test_acc:.4f}')
        print(f'Test Weighted F1: {test_f1:.4f}')
        test_row = pd.DataFrame([{'model': f'{best_tuned_name} ★ TEST', 'cv_primary_mean': test_primary, 'cv_primary_std': None, 'cv_f1_mean': test_f1, 'cv_accuracy_mean': test_acc, 'test_score': test_primary, 'note': 'TEST SET — final evaluation'}])
        leaderboard_2 = pd.concat([leaderboard_1, test_row], ignore_index=True)
        mo.output.append(table(leaderboard_2[['model', 'cv_primary_mean', 'cv_f1_mean', 'cv_accuracy_mean', 'note']]))  # Append test reveal row to leaderboard
    return best_model, best_tuned_name, leaderboard_2, test_primary


