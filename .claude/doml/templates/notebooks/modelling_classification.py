@app.cell
def _(PROJECT_ROOT, fitted_models, mo, np, plt, shap, shap_data_dict):
    with mo.redirect_stdout():
        _reports_dir = PROJECT_ROOT / 'reports'
        _reports_dir.mkdir(exist_ok=True)
        _images_dir = _reports_dir / 'images'
        _images_dir.mkdir(parents=True, exist_ok=True)

        TREE_MODELS = ('RandomForestClassifier', 'XGBClassifier', 'LGBMClassifier')
        LINEAR_MODELS = ('LogisticRegression',)
        SKIP_MODELS = ('DummyClassifier(most_frequent)',)

        for _name, fitted_model in fitted_models.items():
            if _name in SKIP_MODELS:
                print(f"{_name}: skipped (no meaningful SHAP explanation)")
                continue

            X_shap = shap_data_dict[_name]
            # SHAP cost grows with rows x trees; 2,000 seeded rows give a stable ranking.
            if len(X_shap) > 2000:
                X_shap = X_shap.sample(2000, random_state=42)

            try:
                if _name in TREE_MODELS:
                    explainer = shap.TreeExplainer(fitted_model)
                    # Exact TreeSHAP on fully grown forests takes minutes per few hundred
                    # rows; the Saabas approximation is enough for a global ranking.
                    shap_vals = explainer.shap_values(X_shap, approximate='RandomForest' in _name)
                    # Binary: shap_vals is list of 2 arrays — use positive class
                    if isinstance(shap_vals, list) and len(shap_vals) == 2:
                        shap_vals = shap_vals[1]
                    elif isinstance(shap_vals, list):
                        shap_vals = np.array(shap_vals).mean(axis=0)  # multi-class: mean across classes
                elif _name in LINEAR_MODELS:
                    explainer = shap.LinearExplainer(fitted_model, X_shap)
                    shap_vals = explainer.shap_values(X_shap)
                    if isinstance(shap_vals, list):
                        shap_vals = shap_vals[1] if len(shap_vals) == 2 else np.array(shap_vals).mean(axis=0)
                else:
                    background = shap.sample(X_shap, min(100, len(X_shap)))
                    explainer = shap.KernelExplainer(fitted_model.predict_proba, background)
                    shap_vals = explainer.shap_values(X_shap, nsamples=100)
                    if isinstance(shap_vals, list):
                        shap_vals = shap_vals[1] if len(shap_vals) == 2 else np.array(shap_vals).mean(axis=0)

                plt.figure(figsize=(8, 5))
                shap.summary_plot(shap_vals, X_shap, plot_type='bar', show=False,
                                  max_display=10, title=f'SHAP — {_name}')
                safe_name = _name.replace('(', '').replace(')', '').replace(' ', '_')
                plot_path = _images_dir / f'shap_{safe_name}.png'
                plt.savefig(plot_path, bbox_inches='tight', dpi=100)
                plt.close()
                mo.output.append(mo.image(src=str(plot_path)))
                print(f"Saved: {plot_path.relative_to(PROJECT_ROOT)}")

            except Exception as e:
                print(f"{_name}: SHAP failed — {e}")
    return


