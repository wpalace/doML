@app.cell
def _(LogisticRegression, RandomForestClassifier, cross_validate, lgb, xgb):
    def make_objective_clf(model_name, X_tr, y_tr, skf, seed, primary_metric):
        def objective(trial):
            if 'RandomForest' in model_name:
                params = {
                    'n_estimators': trial.suggest_int('n_estimators', 50, 300),
                    'max_depth': trial.suggest_int('max_depth', 3, 15),
                    'min_samples_split': trial.suggest_int('min_samples_split', 2, 10),
                }
                model = RandomForestClassifier(random_state=seed, **params)
            elif 'XGB' in model_name:
                params = {
                    'n_estimators': trial.suggest_int('n_estimators', 50, 300),
                    'max_depth': trial.suggest_int('max_depth', 3, 10),
                    'learning_rate': trial.suggest_float('learning_rate', 0.01, 0.3, log=True),
                    'subsample': trial.suggest_float('subsample', 0.5, 1.0),
                }
                model = xgb.XGBClassifier(random_state=seed, verbosity=0,
                                           eval_metric='logloss', **params)
            elif 'LGBM' in model_name:
                params = {
                    'n_estimators': trial.suggest_int('n_estimators', 50, 300),
                    'max_depth': trial.suggest_int('max_depth', 3, 10),
                    'learning_rate': trial.suggest_float('learning_rate', 0.01, 0.3, log=True),
                    'num_leaves': trial.suggest_int('num_leaves', 20, 150),
                }
                model = lgb.LGBMClassifier(random_state=seed, verbose=-1, **params)
            else:
                params = {'C': trial.suggest_float('C', 0.01, 100.0, log=True)}
                model = LogisticRegression(max_iter=1000, random_state=seed, **params)

            scores = cross_validate(model, X_tr, y_tr, cv=skf, n_jobs=-1,
                                    scoring=primary_metric)
            return scores['test_score'].mean()

        return objective

    return (make_objective_clf,)


@app.cell
def _(table, 
    LogisticRegression,
    RandomForestClassifier,
    SEED,
    X_train,
    leaderboard,
    lgb,
    make_objective_clf,
    mo,
    optuna,
    pd,
    primary_label,
    primary_metric,
    skf,
    top3,
    xgb,
    y_train,
):
    with mo.redirect_stdout():
        tuned_rows = []
        tuned_models = {}
        for model_name in top3:
            print(f'\nTuning {model_name} (30 trials)...')
            study = optuna.create_study(direction='maximize', sampler=optuna.samplers.TPESampler(seed=SEED))
            study.optimize(make_objective_clf(model_name, X_train, y_train, skf, SEED, primary_metric), n_trials=30, show_progress_bar=False)
            best_params = study.best_params
            best_score = study.best_value
            print(f'  Best {primary_label}: {best_score:.4f}  |  Params: {best_params}')
            if 'RandomForest' in model_name:
                _best_model = RandomForestClassifier(random_state=SEED, **best_params)
            elif 'XGB' in model_name:
                _best_model = xgb.XGBClassifier(random_state=SEED, verbosity=0, eval_metric='logloss', **best_params)
            elif 'LGBM' in model_name:
                _best_model = lgb.LGBMClassifier(random_state=SEED, verbose=-1, **best_params)
            else:
                _best_model = LogisticRegression(max_iter=1000, random_state=SEED, **best_params)  # Refit on full training set with best params
            _best_model.fit(X_train, y_train)
            tuned_models[model_name] = _best_model
            tuned_rows.append({'model': f'{model_name} (tuned)', 'cv_primary_mean': round(best_score, 4), 'cv_primary_std': None, 'cv_f1_mean': None, 'cv_accuracy_mean': None, 'test_score': None, 'note': 'Optuna-tuned'})
        tuned_df = pd.DataFrame(tuned_rows)
        leaderboard_1 = pd.concat([leaderboard, tuned_df], ignore_index=True).sort_values('cv_primary_mean', ascending=False).reset_index(drop=True)
        print(f'\n--- UPDATED LEADERBOARD (with tuned, {primary_label}) ---')
