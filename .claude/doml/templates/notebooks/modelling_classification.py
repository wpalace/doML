@app.cell
def _(
    PROJECT_ROOT,
    X_train,
    auc,
    fitted_models,
    is_binary,
    label_binarize,
    mo,
    np,
    plt,
    roc_auc_score,
    roc_curve,
    skf,
    y_train,
):
    with mo.redirect_stdout():
        # ROC Curves — binary: per-model | multi-class: macro one-vs-rest
        # Uses the same first CV validation fold as SHAP (not the sealed test set)

        _first_split = list(skf.split(X_train, y_train))[0]
        __, _val_idx  = _first_split
        X_val_roc   = X_train.iloc[_val_idx]
        y_val_roc   = y_train.iloc[_val_idx]

        fig, ax = plt.subplots(figsize=(8, 6))
        ax.plot([0, 1], [0, 1], 'k--', lw=1.2, label='Random classifier (AUC = 0.50)')

        COLORS = plt.cm.tab10.colors
        for i, (_name, model) in enumerate(fitted_models.items()):
            try:
                if is_binary:
                    y_score   = model.predict_proba(X_val_roc)[:, 1]
                    fpr, tpr, __ = roc_curve(y_val_roc, y_score)
                    model_auc = roc_auc_score(y_val_roc, y_score)
                else:
                    classes   = model.classes_
                    y_bin     = label_binarize(y_val_roc, classes=classes)
                    y_score   = model.predict_proba(X_val_roc)
                    all_fpr   = np.unique(np.concatenate([
                        roc_curve(y_bin[:, j], y_score[:, j])[0]
                        for j in range(len(classes))
                    ]))
                    mean_tpr  = np.mean([
                        np.interp(all_fpr, *roc_curve(y_bin[:, j], y_score[:, j])[:2])
                        for j in range(len(classes))
                    ], axis=0)
                    fpr, tpr  = all_fpr, mean_tpr
                    model_auc = auc(fpr, tpr)

                ls = '--' if 'Dummy' in _name else '-'
                lw = 1.5  if 'Dummy' in _name else 2.0
                ax.plot(fpr, tpr, ls=ls, lw=lw, color=COLORS[i % 10],
                        label=f'{_name}  (AUC = {model_auc:.3f})')

            except Exception as e:
                print(f'{_name}: ROC skipped — {e}')

        ax.set_xlim([0, 1]); ax.set_ylim([0, 1.02])
        ax.set_xlabel('False Positive Rate')
        ax.set_ylabel('True Positive Rate')
        roc_title = 'Binary ROC Curves' if is_binary else 'Macro OvR ROC Curves'
        ax.set_title(f'{roc_title} — CV validation fold')
        ax.legend(loc='lower right', fontsize=9)
        ax.grid(True, alpha=0.3)

        _reports_dir = PROJECT_ROOT / 'reports'
        _reports_dir.mkdir(exist_ok=True)
        _images_dir = _reports_dir / 'images'
        _images_dir.mkdir(parents=True, exist_ok=True)
        roc_path = _images_dir / 'roc_curves.png'
        plt.savefig(roc_path, bbox_inches='tight', dpi=120)
        plt.close()
        mo.output.append(mo.image(src=str(roc_path)))
        print(f'ROC plot saved: {roc_path.relative_to(PROJECT_ROOT)}')
    return


