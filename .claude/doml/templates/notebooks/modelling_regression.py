@app.cell
def _(PROJECT_ROOT, fitted_models, mo, plt, shap, shap_data):
    with mo.redirect_stdout():
        reports_dir = PROJECT_ROOT / 'reports'
        reports_dir.mkdir(exist_ok=True)
        images_dir = reports_dir / 'images'
        images_dir.mkdir(parents=True, exist_ok=True)

        TREE_MODELS = ('RandomForestRegressor', 'XGBRegressor', 'LGBMRegressor')
        LINEAR_MODELS = ('LinearRegression', 'Ridge', 'Lasso')
        SKIP_MODELS = ('DummyRegressor(mean)',)

        for _name, fitted_model in fitted_models.items():
            if _name in SKIP_MODELS:
                print(f"{_name}: skipped (no meaningful SHAP explanation)")
                continue

            X_shap = shap_data[_name]
            # SHAP cost grows with rows x trees (RandomForest on 16k rows took >20 min on one core).
            # 2,000 seeded rows give a stable global importance ranking.
            if len(X_shap) > 2000:
                X_shap = X_shap.sample(2000, random_state=42)

            try:
                if _name in TREE_MODELS:
                    explainer = shap.TreeExplainer(fitted_model)
                    # Exact TreeSHAP on fully grown forests takes minutes per few hundred
                    # rows; the Saabas approximation is enough for a global ranking.
                    shap_values = explainer.shap_values(X_shap, approximate='RandomForest' in _name)
                elif _name in LINEAR_MODELS:
                    explainer = shap.LinearExplainer(fitted_model, X_shap)
                    shap_values = explainer.shap_values(X_shap)
                else:
                    background = shap.sample(X_shap, min(100, len(X_shap)))
                    explainer = shap.KernelExplainer(fitted_model.predict, background)
                    shap_values = explainer.shap_values(X_shap, nsamples=100)

                plt.figure(figsize=(8, 5))
                shap.summary_plot(shap_values, X_shap, plot_type='bar', show=False,
                                  max_display=10, title=f'SHAP — {_name}')
                safe_name = _name.replace('(', '').replace(')', '').replace(' ', '_')
                plot_path = images_dir / f'shap_{safe_name}.png'
                plt.savefig(plot_path, bbox_inches='tight', dpi=100)
                plt.close()
                mo.output.append(mo.image(src=str(plot_path)))
                print(f"Saved: {plot_path.relative_to(PROJECT_ROOT)}")

            except Exception as e:
                print(f"{_name}: SHAP failed — {e}")
    return


