@app.cell
def _(KFold, SEED, X_train, cross_validate, mo, models, n_folds, pd, y_train, table):
    with mo.redirect_stdout():
        kf = KFold(n_splits=n_folds, shuffle=True, random_state=SEED)
        leaderboard_rows = []

        # Store fitted models and first-split data for SHAP
        fitted_models = {}
        shap_data = {}

        for _name, model in models.items():
            scores = cross_validate(
                model, X_train, y_train, cv=kf, n_jobs=-1,
                scoring={
                    'rmse':  'neg_root_mean_squared_error',
                    'mae':   'neg_mean_absolute_error',
                    'r2':    'r2',
                },
                return_estimator=True,
                return_train_score=False,
            )

            rmse_mean = -scores['test_rmse'].mean()
            rmse_std  = scores['test_rmse'].std()
            mae_mean  = -scores['test_mae'].mean()
            r2_mean   = scores['test_r2'].mean()

            leaderboard_rows.append({
                'model':         _name,
                'cv_rmse_mean':  round(rmse_mean, 4),
                'cv_rmse_std':   round(rmse_std, 4),
                'cv_mae_mean':   round(mae_mean, 4),
                'cv_r2_mean':    round(r2_mean, 4),
                'test_score':    None,
                'note':          'CV',
            })

            # Save first-fold fitted model + validation split for SHAP
            first_split = list(kf.split(X_train))[0]
            _, val_idx = first_split
            X_val_shap = X_train.iloc[val_idx]
            fitted_models[_name] = scores['estimator'][0]
            shap_data[_name] = X_val_shap

            print(f"{_name:30s}  RMSE={rmse_mean:.4f} ±{rmse_std:.4f}  MAE={mae_mean:.4f}  R²={r2_mean:.4f}")

        leaderboard = pd.DataFrame(leaderboard_rows).sort_values('cv_rmse_mean').reset_index(drop=True)
        print("\n--- LEADERBOARD ---")
        mo.output.append(table(leaderboard[['model','cv_rmse_mean','cv_rmse_std','cv_mae_mean','cv_r2_mean']]))
    return fitted_models, kf, leaderboard, shap_data


