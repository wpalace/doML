@app.cell
def _(
    Lasso,
    LinearRegression,
    RandomForestRegressor,
    Ridge,
    cross_validate,
    lgb,
    xgb,
):
    def make_objective(model_name, X_tr, y_tr, kf, seed):
        def objective(trial):
            if 'RandomForest' in model_name:
                params = {
                    'n_estimators': trial.suggest_int('n_estimators', 50, 300),
                    'max_depth': trial.suggest_int('max_depth', 3, 15),
                    'min_samples_split': trial.suggest_int('min_samples_split', 2, 10),
                }
                model = RandomForestRegressor(random_state=seed, **params)
            elif 'XGB' in model_name:
                params = {
                    'n_estimators': trial.suggest_int('n_estimators', 50, 300),
                    'max_depth': trial.suggest_int('max_depth', 3, 10),
                    'learning_rate': trial.suggest_float('learning_rate', 0.01, 0.3, log=True),
                    'subsample': trial.suggest_float('subsample', 0.5, 1.0),
                }
                model = xgb.XGBRegressor(random_state=seed, verbosity=0, **params)
            elif 'LGBM' in model_name:
                params = {
                    'n_estimators': trial.suggest_int('n_estimators', 50, 300),
                    'max_depth': trial.suggest_int('max_depth', 3, 10),
                    'learning_rate': trial.suggest_float('learning_rate', 0.01, 0.3, log=True),
                    'num_leaves': trial.suggest_int('num_leaves', 20, 150),
                }
                model = lgb.LGBMRegressor(random_state=seed, verbose=-1, **params)
            elif 'Ridge' in model_name:
                params = {'alpha': trial.suggest_float('alpha', 0.01, 100.0, log=True)}
                model = Ridge(**params)
            elif 'Lasso' in model_name:
                params = {'alpha': trial.suggest_float('alpha', 0.001, 10.0, log=True)}
                model = Lasso(max_iter=10000, **params)
            else:
                model = LinearRegression()

            scores = cross_validate(model, X_tr, y_tr, cv=kf, n_jobs=-1,
                                    scoring='neg_root_mean_squared_error')
            return -scores['test_score'].mean()

        return objective

    return (make_objective,)


@app.cell
def _(table, 
    Lasso,
    LinearRegression,
    RandomForestRegressor,
    Ridge,
    SEED,
    X_train,
    kf,
    leaderboard,
    lgb,
    make_objective,
    mo,
    optuna,
    pd,
    top3,
    xgb,
    y_train,
):
    with mo.redirect_stdout():
        tuned_rows = []
        tuned_models = {}
        for model_name in top3:
            print(f'\nTuning {model_name} (30 trials)...')
            study = optuna.create_study(direction='minimize', sampler=optuna.samplers.TPESampler(seed=SEED))
            study.optimize(make_objective(model_name, X_train, y_train, kf, SEED), n_trials=30, show_progress_bar=False)
            best_params = study.best_params
            best_rmse = study.best_value
            print(f'  Best RMSE: {best_rmse:.4f}  |  Params: {best_params}')
            if 'RandomForest' in model_name:
                _best_model = RandomForestRegressor(random_state=SEED, **best_params)
            elif 'XGB' in model_name:
                _best_model = xgb.XGBRegressor(random_state=SEED, verbosity=0, **best_params)
            elif 'LGBM' in model_name:
                _best_model = lgb.LGBMRegressor(random_state=SEED, verbose=-1, **best_params)  # Refit on full training set with best params
            elif 'Ridge' in model_name:
                _best_model = Ridge(**best_params)
            elif 'Lasso' in model_name:
                _best_model = Lasso(max_iter=10000, **best_params)
            else:
                _best_model = LinearRegression()
            _best_model.fit(X_train, y_train)
            tuned_models[model_name] = _best_model
            tuned_rows.append({'model': f'{model_name} (tuned)', 'cv_rmse_mean': round(best_rmse, 4), 'cv_rmse_std': None, 'cv_mae_mean': None, 'cv_r2_mean': None, 'test_score': None, 'note': 'Optuna-tuned'})
        tuned_df = pd.DataFrame(tuned_rows)
        leaderboard_1 = pd.concat([leaderboard, tuned_df], ignore_index=True).sort_values('cv_rmse_mean').reset_index(drop=True)
        print('\n--- UPDATED LEADERBOARD (with tuned) ---')
        mo.output.append(table(leaderboard_1[['model', 'cv_rmse_mean', 'note']]))
    return leaderboard_1, tuned_df, tuned_models


